// codecPair resolves this generation's immutable codec pair. A zero-value
// Log (tests constructing the struct directly) speaks the legacy pair.
func (l *Log) codecPair() (record, control string) {
	if l.recordCodec == "" {
		return wal.PFR1Codec, ctlrec.PFC1Codec
	}
	return l.recordCodec, l.controlCodec
}

// RecordCodec identifies this epoch's record encoding.
func (l *Log) RecordCodec() string { record, _ := l.codecPair(); return record }

// ControlCodec identifies this epoch's control-payload encoding.
func (l *Log) ControlCodec() string { _, control := l.codecPair(); return control }

// Epoch is the journal generation's digest-chain epoch (an identity, not a
// second lease clock).
func (l *Log) Epoch() uint64 { return l.epoch }

// GenerationID names the claimed journal generation.
func (l *Log) GenerationID() string { return l.generationID }

// BaseCommitID is the exact manifest anchor cold recovery loads (advanced
// only by proven logical trims).
func (l *Log) BaseCommitID() string {
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.baseCommitID
}

// BaseDigest is the exact lowercase SHA-256 digest-chain value at
// CompactedThrough. Startup presents it to the independent history-serving
// proof so a commit id alone can never select a base.
func (l *Log) BaseDigest() string {
	l.mu.Lock()
	defer l.mu.Unlock()
	return hex.EncodeToString(l.baseDigest[:])
}

// Watermark is the exclusive upper bound of reserved LSNs (staged included).
func (l *Log) Watermark() uint64 {
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.nextSeq
}

// DurableHead returns the exact exclusive database-durable revision. It does
// not include locally reserved/staged records. This is an observation only:
// lifecycle callers must close admission and use SuspendExact to atomically
// verify the same revision while changing the durable generation state.
func (l *Log) DurableHead() (nextSeq uint64, tipDigest string) {
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.durableSeq, hex.EncodeToString(l.durableTip[:])
}

// CompactedThrough is the journal's logical base (records below it are
// checkpoint-covered and may be physically deleted at any time).
func (l *Log) CompactedThrough() uint64 {
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.baseSeq
}

// BacklogBytes reports durable backlog plus uncommitted staging.
func (l *Log) BacklogBytes() int64 {
	l.mu.Lock()
	defer l.mu.Unlock()
	if total, ok := addNonnegativeInt64(l.backlogBytes, l.stagedBytes); ok {
		return total
	}
	// Both components are non-negative database/admission facts. Saturating
	// keeps observability and admission fail-closed instead of wrapping to a
	// negative value should a corrupt or future-expanded bound reach int64.
	return int64(^uint64(0) >> 1)
}

// SetCapacity installs an ADVISORY client-side backlog bound (0 clears it).
// The authoritative quota lives in the database (identical for every replica);
// the advisory bound can only be stricter.
func (l *Log) SetCapacity(bytes int64) {
	l.mu.Lock()
	l.advisoryCapacity = bytes
	l.mu.Unlock()
}

// QuotaBytes reports the database-owned backlog byte quota mirrored from the
// last claim/append/trim (the advisory bound, when stricter, wins so statfs
// reflects the bound writes actually hit).
func (l *Log) QuotaBytes() int64 {
	l.mu.Lock()
	defer l.mu.Unlock()
	if l.advisoryCapacity > 0 && (l.quotaBytes == 0 || l.advisoryCapacity < l.quotaBytes) {
		return l.advisoryCapacity
	}
	return l.quotaBytes
}

// OverCapacity reports whether admission must stop BEFORE reserving more
// intents: the database quota (mirrored from the last claim/append/trim),
// the advisory bound, or the staging-memory cap would be exceeded.
func (l *Log) OverCapacity() bool {
	l.mu.Lock()
	defer l.mu.Unlock()
	pendingBytes, bytesOK := addNonnegativeInt64(l.backlogBytes, l.stagedBytes)
	pendingRecords, recordsOK := addNonnegativeInt64(l.backlogRecords, int64(len(l.staged)))
	if !bytesOK || !recordsOK {
		return true
	}
	if l.quotaBytes > 0 && pendingBytes >= l.quotaBytes {
		return true
	}
	if l.quotaRecords > 0 && pendingRecords >= l.quotaRecords {
		return true
	}
	if l.advisoryCapacity > 0 && pendingBytes >= l.advisoryCapacity {
		return true
	}
	return l.stagedBytes >= l.cfg.MaxStagedBytes
}

// Poison permanently fences the log.
func (l *Log) Poison() { l.poison(fmt.Errorf("remotejournal: poisoned by caller")) }

func (l *Log) poison(cause error) {
	l.mu.Lock()
	defer l.mu.Unlock()
	l.poisonLocked(cause)
}

func (l *Log) poisonLocked(cause error) {
	if l.poisoned {
		return
	}
	l.poisoned = true
	l.poisonCause = cause
	close(l.poisonedCh)
}

// IsPoisoned reports whether the log refuses further mutations.
func (l *Log) IsPoisoned() bool {
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.poisoned
}

// PoisonedCh is closed the moment the log is fenced.
func (l *Log) PoisonedCh() <-chan struct{} { return l.poisonedCh }

// DurabilityFacts returns the database's verifiable durability configuration
// for honest readiness evidence (a configuration string alone is not HA).
func (l *Log) DurabilityFacts(ctx context.Context) (map[string]any, error) {
	raw, err := l.callJSONB(ctx, `SELECT pfj.durability_facts()`)
	if err != nil {
		return nil, fmt.Errorf("remotejournal: durability facts: %w", err)
	}
	var facts map[string]any
	if err := json.Unmarshal(raw, &facts); err != nil {
		return nil, fmt.Errorf("remotejournal: decode durability facts: %w", err)
	}
	return facts, nil
}
