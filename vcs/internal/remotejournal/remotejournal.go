// Package remotejournal is the production wal.DurableLog: a fenced
// PostgreSQL journal reached directly from Go over pgx/v5, exclusively through
// the narrowly scoped SECURITY DEFINER functions installed by metadata-db
// migration 009_remote_journal (schema pfj). It is the ONLY production log
// implementation; the file WAL (+ paired replication) remains an explicit
// development / offline-mount / fault-test implementation.
//
// Properties the implementation upholds:
//
//   - No local state. An authority holds journal truth only in the
//     database plus bounded process memory (uncommitted staging and mirrors of
//     remote facts). It never creates .wal/.meta/.transition/.opstate files.
//   - Canonical bytes, encoded once. Every record is encoded to PFR1 exactly
//     once at staging; the identical bytes are the DB row, the hash/chain
//     input, the duplicate-comparison identity, and the retry body.
//   - Durable-before-visible. AppendBatchBuffered reserves contiguous LSNs
//     and stages bytes without durability; CommitThrough returns nil only
//     after a committed database transaction covers the range.
//   - UNKNOWN outcomes are resolved, not guessed. A lost commit response is
//     retried with byte-identical groups: the server folds byte-identical
//     duplicates (before quota) so the retry converges on the truth. Only a
//     proven fence/conflict/integrity failure poisons the log.
//   - Bounded everything. One write ≤ 1 MiB, one intent ≤ 8 MiB, one commit
//     group ≤ 128 records / 16 MiB, one replay page ≤ 256 records / 16 MiB,
//     and staging memory is capped.
//   - Database-time fencing. Every mutating call presents the branch writer
//     lease + fencing token + capability; the SQL layer validates them against
//     clock_timestamp(), never a caller clock.
package remotejournal

