// Command generate derives the hand codec's exact grammar from pfslocal.proto.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"

	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
)

func main() {
	root := flag.String("root", "..", "repository root")
	flag.Parse()
	temp, err := os.CreateTemp("", "pfslocal-descriptor-*.pb")
	must(err)
	path := temp.Name()
	must(temp.Close())
	defer os.Remove(path)
	command := exec.Command("protoc", "-I", *root, "--descriptor_set_out="+path, filepath.Join(*root, "pfslocal/pfslocal.proto"))
	output, err := command.CombinedOutput()
	if err != nil {
		panic(fmt.Sprintf("protoc: %v: %s", err, output))
	}
	raw, err := os.ReadFile(path)
	must(err)
	var set descriptorpb.FileDescriptorSet
	must(proto.Unmarshal(raw, &set))
	file := set.File[0]
	enums := map[string][]int32{}
	var collect func(string, []*descriptorpb.EnumDescriptorProto, []*descriptorpb.DescriptorProto)
	collect = func(prefix string, ee []*descriptorpb.EnumDescriptorProto, mm []*descriptorpb.DescriptorProto) {
		for _, e := range ee {
			for _, v := range e.Value {
				enums[prefix+e.GetName()] = append(enums[prefix+e.GetName()], v.GetNumber())
			}
		}
		for _, m := range mm {
			collect(prefix+m.GetName()+".", m.EnumType, m.NestedType)
		}
	}
	collect("."+file.GetPackage()+".", file.EnumType, file.MessageType)
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by go run ./internal/pfslocal/generate -root ..; DO NOT EDIT.\npackage pfslocal")
	schema, err := os.ReadFile(filepath.Join(*root, "pfslocal/pfslocal.proto"))
	must(err)
	fmt.Fprintf(&b, "const localSchemaSHA256 = %q\n", fmt.Sprintf("%x", sha256.Sum256(schema)))
	fmt.Fprintln(&b, "var localSchema = map[string][]localField{")
	var emit func(string, []*descriptorpb.DescriptorProto)
	emit = func(prefix string, mm []*descriptorpb.DescriptorProto) {
		for _, m := range mm {
			fmt.Fprintf(&b, "%q: {\n", prefix+m.GetName())
			for _, f := range m.Field {
				kind := "v"
				switch f.GetType() {
				case descriptorpb.FieldDescriptorProto_TYPE_UINT32:
					kind = "u"
				case descriptorpb.FieldDescriptorProto_TYPE_INT32:
					kind = "i"
				case descriptorpb.FieldDescriptorProto_TYPE_INT64:
					kind = "j"
				case descriptorpb.FieldDescriptorProto_TYPE_BOOL:
					kind = "b"
				case descriptorpb.FieldDescriptorProto_TYPE_STRING:
					kind = "s"
				case descriptorpb.FieldDescriptorProto_TYPE_BYTES:
					kind = "x"
				case descriptorpb.FieldDescriptorProto_TYPE_MESSAGE:
					kind = "m"
				case descriptorpb.FieldDescriptorProto_TYPE_ENUM:
					kind = "e"
				case descriptorpb.FieldDescriptorProto_TYPE_UINT64:
				default:
					panic("unsupported kind: " + f.GetType().String())
				}
				oneof := 0
				if f.OneofIndex != nil {
					oneof = int(f.GetOneofIndex()) + 1
				}
				fmt.Fprintf(&b, "{number:%d, name:%q, kind:%s, repeated:%t, oneof:%d, message:%q", f.GetNumber(), f.GetName(), strconv.QuoteRune(rune(kind[0])), f.GetLabel() == descriptorpb.FieldDescriptorProto_LABEL_REPEATED, oneof, f.GetTypeName())
				if kind == "e" {
					fmt.Fprint(&b, ", values:[]int32{")
					for _, v := range enums[f.GetTypeName()] {
						fmt.Fprintf(&b, "%d,", v)
					}
					fmt.Fprint(&b, "}")
				}
				fmt.Fprintln(&b, "},")
			}
			fmt.Fprintln(&b, "},")
			emit(prefix+m.GetName()+".", m.NestedType)
		}
	}
	emit("."+file.GetPackage()+".", file.MessageType)
	fmt.Fprintln(&b, "}")
	formatted, err := format.Source(b.Bytes())
	must(err)
	must(os.WriteFile(filepath.Join(*root, "vcs/internal/pfslocal/wire_schema.go"), formatted, 0644))
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
